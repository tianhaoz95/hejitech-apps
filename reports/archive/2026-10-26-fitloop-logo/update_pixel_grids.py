# 1. Update round2_cands.py
r2_path = "reports/archive/2026-10-26-fitloop-logo/round2_cands.py"
with open(r2_path, "r", encoding="utf-8") as f:
    r2_content = f.read()

# Pattern matching each candidate call in round2_cands.py:
# add_r2( "cand-id", ... """grid""" )
for cid, grid in new_grids.items():
    if cid == "vital-sprout":
        continue
    # Replace the grid string in add_r2( cid, ... )
    # Look for add_r2(\s*"cid" ... """[\s#.]+"""\s*\)
    pattern = rf'(add_r2\(\s*"{cid}"[\s\S]*?""")([\s#.]+?)("""\s*\))'
    match = re.search(pattern, r2_content)
    if match:
        r2_content = r2_content[:match.start(2)] + "\n" + grid + "\n" + r2_content[match.end(2):]
        print(f"Updated grid for {cid} in round2_cands.py")
    else:
        print(f"WARNING: Could not find match for {cid} in round2_cands.py")

with open(r2_path, "w", encoding="utf-8") as f:
    f.write(r2_content)

# 2. Update even_grids.py for vital-sprout
eg_path = "reports/archive/2026-10-26-fitloop-logo/even_grids.py"
with open(eg_path, "r", encoding="utf-8") as f:
    eg_content = f.read()

eg_content = re.sub(
    r'(grids\["vital-sprout"\]\s*=\s*""")[^"]+(""")',
    rf'\g<1>\n{new_grids["vital-sprout"]}\n\g<2>',
    eg_content
)
with open(eg_path, "w", encoding="utf-8") as f:
    f.write(eg_content)
print("Updated vital-sprout in even_grids.py")
