#!/usr/bin/env node
// The card-authoring guide is written in packages/core/guide/card-authoring-guide.md and served
// live by get_card_authoring_guide. This copies it into packages/core/src/guide.gen.ts (a string
// every runtime can import: Worker, web pages, tests). Edit the .md, then run this.
//   node projects/g2digest/scripts/sync-guide.mjs           # write
//   node projects/g2digest/scripts/sync-guide.mjs --check   # CI: fail if out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const core = join(dirname(fileURLToPath(import.meta.url)), "../packages/core");
const md = readFileSync(join(core, "guide/card-authoring-guide.md"), "utf8");
const version = md.match(/^guide_version: (\d+\.\d+)$/m)?.[1];
if (!version) throw new Error("card-authoring-guide.md: no `guide_version: x.y` line");
const out = `// Generated by projects/g2digest/scripts/sync-guide.mjs from guide/card-authoring-guide.md. Don't edit.
export const GUIDE_VERSION = ${JSON.stringify(version)};
export const GUIDE = ${JSON.stringify(md)};
`;
const target = join(core, "src/guide.gen.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("!! packages/core/src/guide.gen.ts is out of date: run node projects/g2digest/scripts/sync-guide.mjs");
    process.exit(1);
  }
  console.log(`guide ${version} in sync`);
} else {
  writeFileSync(target, out);
  console.log(`wrote guide ${version} → src/guide.gen.ts`);
}
