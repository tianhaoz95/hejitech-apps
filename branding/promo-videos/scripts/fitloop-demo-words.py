# Word timings for the FitLoop walkthrough's captions: faster-whisper reads each narration clip back
# (checks the words) and gives word times; the caption shows the written words ("FitLoop", "MCP", "AI", "R1", "G2", "HUD"),
# mapped onto the spoken ones in order. Writes src/fitloop-demo/voiceover.ts.
#
#   <venv>/bin/python -I branding/promo-videos/scripts/fitloop-demo-words.py \
#     /Volumes/DATA/GitHub/hejitech-apps/branding/promo-videos/public/fitloop-demo af_sarah \
#     branding/promo-videos/src/fitloop-demo/voiceover.ts
import sys, json, re, importlib.util, numpy as np, soundfile as sf
from faster_whisper import WhisperModel

folder, voice, out = sys.argv[1:4]
# Read LINES from the narration script without running it.
src = open(__file__.replace("-words.py", "-vo.py")).read()
LINES = eval(src[src.index("LINES = {") + len("LINES = "): src.index("}\n", src.index("LINES = {")) + 1])
SHOW = {
    "Fit Loop": "FitLoop",
    "M C P": "MCP",
    "A I": "AI",
    "R one": "R1",
    "G two": "G2",
    "H U D": "HUD",
    "six digit": "six-digit",
    "nine line": "9-line",
    "Tomorrows": "Tomorrow's",
}

model = WhisperModel("small.en", device="cpu", compute_type="int8")
res = {}
for key, text in LINES.items():
    shown = text
    for a, b in SHOW.items(): shown = shown.replace(a, b)
    audio, sr = sf.read(f"{folder}/vo-{voice}-{key}.wav", dtype="float32")
    segs, _ = model.transcribe(audio, language="en", word_timestamps=True, beam_size=5)
    spoken = [w for s in segs for w in s.words]
    heard = " ".join(w.word.strip() for w in spoken)
    want = shown.split()
    # Map written words onto spoken ones: same count → one to one; else spread by length over the speech span.
    if len(spoken) == len(want):
        words = [[w, round(s.start, 2), round(s.end, 2)] for w, s in zip(want, spoken)]
    elif spoken:
        a, b = spoken[0].start, spoken[-1].end
        lens = np.array([len(w) + 1 for w in want], float)
        edges = a + np.concatenate([[0], np.cumsum(lens)]) / lens.sum() * (b - a)
        words = [[w, round(edges[i], 2), round(edges[i + 1], 2)] for i, w in enumerate(want)]
    else:
        dur = len(audio) / sr
        lens = np.array([len(w) + 1 for w in want], float)
        edges = np.concatenate([[0], np.cumsum(lens)]) / lens.sum() * dur
        words = [[w, round(edges[i], 2), round(edges[i + 1], 2)] for i, w in enumerate(want)]
    res[key] = {"dur": round(len(audio) / sr, 2), "words": words}

ts = f"""// Generated by scripts/fitloop-demo-words.py with faster-whisper. Do not edit by hand.
export type Word = [word: string, start: number, end: number];
export type LineTiming = {{ dur: number; words: Word[] }};

export const LINES: Record<string, LineTiming> = {json.dumps(res, indent=2)};
"""
open(out, "w").write(ts)
print(f"wrote {len(res)} line timings to {out}")
